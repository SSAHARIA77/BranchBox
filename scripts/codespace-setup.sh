#!/bin/sh
# One-command setup inside a GitHub Codespace:
#   1. writes projects/online-boutique/.env (token, repository, public URL)
#   2. starts Online Boutique + BranchBox
#   3. makes the shop (8080) and controller (8090) ports public
#   4. prints what teammates need
#
# Usage:  ./scripts/codespace-setup.sh [repository-url]
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
envfile="$root/projects/online-boutique/.env"
repo="${1:-https://github.com/SSAHARIA77/GoogleOnlineBoutique.git}"

if [ -z "${CODESPACE_NAME:-}" ]; then
    echo "error: this script is meant to run inside a GitHub Codespace" >&2
    exit 1
fi
domain="${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN:-app.github.dev}"
shop_url="https://${CODESPACE_NAME}-8080.${domain}"
api_url="https://${CODESPACE_NAME}-8090.${domain}"

if [ ! -f "$envfile" ]; then
    token=$(openssl rand -hex 16)
    cat > "$envfile" <<EOF
# Generated by scripts/codespace-setup.sh
# Codespaces port forwarding connects to localhost, so nothing listens publicly
# except through GitHub's authenticated/visibility-controlled forwarding.
BB_BIND_ADDRESS=127.0.0.1
BB_EDGE_DOMAIN=localhost
BB_PUBLIC_URL=$shop_url
BB_API_TOKEN=$token
BB_REPOSITORY_URL=$repo
EOF
    echo "Wrote $envfile"
else
    echo "Using existing $envfile"
fi

"$root/scripts/up.sh"

echo "Making ports 8080 and 8090 public..."
if ! gh codespace ports visibility 8080:public 8090:public -c "$CODESPACE_NAME" >/dev/null 2>&1; then
    echo "  Could not change visibility automatically. In the PORTS tab, right-click"
    echo "  ports 8080 and 8090 -> Port Visibility -> Public."
fi

token=$(grep '^BB_API_TOKEN=' "$envfile" | cut -d= -f2)
cat <<EOF

============================================================
 BranchBox is running in this Codespace.

 Production shop:   $shop_url
 Sandbox picker:    $shop_url/__branchbox

 Teammates (PowerShell, then open a new terminal):
   setx BRANCHBOX_CONTROLLER $api_url
   setx BRANCHBOX_TOKEN $token

 Keep the token private. The codespace stops after its idle timeout
 (GitHub -> Settings -> Codespaces -> Default idle timeout).
============================================================
EOF
